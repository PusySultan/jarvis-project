    @Override
    public Object getGroupIndex(String[] allWords)
    {
        int score = 0;
        int tempScore = 0;
        String strKosgu = null;

        for (Map.Entry<String,List<String>> group : kosgu.entrySet())
        {
            for (String word : allWords)
            {
                if(group.getValue().contains(word))
                {
                    tempScore += word.length();
                }
            }

            if(tempScore > score)
            {
                score = tempScore;
                strKosgu = group.getKey();
            }

            tempScore = 0;
        }

        return strKosgu == null ? "null" : strKosgu;
    }
