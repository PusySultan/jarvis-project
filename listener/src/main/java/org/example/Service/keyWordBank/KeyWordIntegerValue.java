    private static void fillMap(Integer number, List<String> words)
    {
        for (String word : words) {
            NUMBER_WORDS.put(word.toLowerCase(), number);
        }
    }

    @Override
    public Integer getGroupIndex(String[] allWords)
    {
        int kvr = 0;

        for(String word : allWords)
        {
            if(NUMBER_WORDS.containsKey(word))
            {
                kvr += NUMBER_WORDS.get(word);
            }
        }

        return kvr;
    }
